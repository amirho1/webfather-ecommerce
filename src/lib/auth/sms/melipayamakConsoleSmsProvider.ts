import type { SmsProvider, SmsSendResult } from './smsProvider'

export interface MelipayamakConsoleOptions {
  jwt?: string
  token?: string
  endpoint?: string
}

/**
 * Dispatches one-time verification codes (OTP) via Melipayamak's modern Console Token / JWT API.
 * Uses endpoint: POST https://console.melipayamak.com/api/send/otp/<TOKEN>
 */
export default class MelipayamakConsoleSmsProvider implements SmsProvider {
  private readonly jwt?: string
  private readonly endpoint: string

  /**
   * Initializes the Melipayamak Console SMS provider.
   *
   * @param options - Configuration options containing the JWT/Token or custom endpoint.
   */
  constructor(options?: MelipayamakConsoleOptions) {
    this.jwt = options?.jwt ?? options?.token ?? process.env.MELIPAYAMAK_JWT
    this.endpoint = options?.endpoint ?? 'https://console.melipayamak.com/api/send/otp'
  }

  /**
   * Sends an OTP verification request to a recipient mobile phone.
   *
   * @param phone - The destination Iranian mobile number (e.g. 09123456789).
   * @param code - Optional fallback code generated by the application.
   * @returns A promise resolving with the delivered OTP code if generated by the provider.
   */
  async sendOtp(phone: string, code?: string): Promise<SmsSendResult> {
    if (!this.jwt) {
      throw new Error('Melipayamak JWT is not configured')
    }

    const trimmedJwt = this.jwt.trim()
    const url = `${this.endpoint.replace(/\/+$/, '')}/${encodeURIComponent(trimmedJwt)}`

    const response = await fetch(url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        to: phone,
      }),
      signal: AbortSignal.timeout(10000),
      cache: 'no-store',
    })

    const raw = await response.text()
    let data: unknown
    try {
      data = JSON.parse(raw)
    } catch {
      if (!response.ok) {
        throw new Error(`Melipayamak HTTP ${response.status}`)
      }
      throw new Error(`Melipayamak returned unparseable response: ${raw.slice(0, 64)}`)
    }

    const record = data && typeof data === 'object' ? (data as Record<string, unknown>) : null
    const statusStr = typeof record?.status === 'string' ? record.status.trim() : ''
    const returnedCode =
      record && record.code !== undefined && record.code !== null ? String(record.code).trim() : ''

    if (!response.ok) {
      if (statusStr) {
        throw new Error(`Melipayamak rejected OTP: ${statusStr}`)
      }
      throw new Error(`Melipayamak HTTP ${response.status}`)
    }

    if (!record) {
      throw new Error('Melipayamak returned invalid response')
    }

    const isKnownSuccess = /^(عملیات موفق|موفق|ok|success)$/i.test(statusStr)
    const isExplicitError =
      statusStr.length > 0 &&
      (/(معتبر نیست|مستلزم|ارسال نشده|خطا|نامعتبر)/i.test(statusStr) ||
        (!isKnownSuccess && !returnedCode))

    if (isExplicitError) {
      throw new Error(`Melipayamak rejected OTP: ${statusStr}`)
    }

    return {
      code: returnedCode || code,
    }
  }
}
